#!/bin/bash
# ==============================================================================
# ПОЛНЫЙ БЭКАП VS CODE + ОТПРАВКА В GIT (одним скриптом)
# ==============================================================================
# Что делает: 
# 1. Запускает backup.sh (сохраняет настройки и список расширений)
# 2. Копирует обновленные файлы в папку проекта
# 3. Делает коммит в Git
# 4. Отправляет на GitHub
# ==============================================================================

set -e

BACKUP_DIR="$HOME/projects/animated-music-clip/vscode-backup"
PROJECT_DIR="$HOME/projects/animated-music-clip"

echo "[1/4] Сохраняю настройки VS Code..."
cd "$BACKUP_DIR"
bash backup.sh

echo "[2/4] Перехожу в папку проекта..."
cd "$PROJECT_DIR"

echo "[3/4] Фиксирую изменения в Git..."
# Добавляем только папку бэкапа, чтобы не захватить лишний мусор
git add vscode-backup
# Проверяем, есть ли что коммитить (чтобы скрипт не падал с ошибкой, если изменений нет)
if git diff --cached --quiet; then
    echo "Изменений нет, коммит не требуется."
else
    git commit -m "Auto-backup VS Code: $(date +'%Y-%m-%d %H:%M')"
fi

echo "[4/4] Отправляю на GitHub..."
git push

echo ""
echo "ГОТОВО! Настройки сохранены и отправлены в облако."
